import pandas as pd
import numpy as np
from pathlib import Path

lead = pd.read_csv("experiments/leaderboard.csv")
by_cat = pd.read_csv("experiments/leaderboard_by_category.csv")
by_veg = pd.read_csv("experiments/leaderboard_by_vegetable.csv")

# 1. Per-Horizon Significance Table vs Naive for Key Models
print("=== PER-HORIZON SIGNIFICANCE SUMMARY (Selected & Top Models vs Naive) ===")
key_models = [
    "auto_arima", "sarimax", "prophet", "lasso", "ridge", "elastic_net",
    "lightgbm", "xgboost", "catboost", "extra_trees",
    "mlp", "lstm", "gru", "tcn_1d", "tft_lite",
    "simple_average_top3", "stacking_meta_learner", "best_per_category"
]

sig_rows = []
for h in [1, 4, 8, 12]:
    sub = lead[(lead["horizon"] == h) & (lead["split"] == "test")].sort_values("MASE").drop_duplicates(subset=["model"]).set_index("model")
    naive_mase = sub.loc["naive", "MASE"]
    for m in key_models:
        if m in sub.index:
            r = sub.loc[m]
            sig_rows.append({
                "horizon": h,
                "model": m,
                "test_MASE": r["MASE"],
                "skill_vs_naive": r["Skill_vs_Naive"],
                "diff_naive_ci": r["Diff_Naive_CI_95"],
                "DM_stat": r["DM_stat_vs_Naive"],
                "DM_pval_raw": r["DM_pval_vs_Naive"],
                "DM_pval_Holm": r["DM_pval_Holm_vs_Naive"],
                "sig_05": r["DM_pval_Holm_vs_Naive"] < 0.05
            })

df_sig = pd.DataFrame(sig_rows)
df_sig.to_csv("results/tables/per_horizon_significance.csv", index=False)
print("Saved results/tables/per_horizon_significance.csv")

# 2. Per-Category Summary Table (h=4) including Naive and Lasso
print("\n=== PER-CATEGORY SUMMARY TABLE (h=4) ===")
sub_cat = by_cat[by_cat["horizon"] == 4].copy()
# Filter for key models
cat_key_models = ["naive", "auto_arima", "lasso", "lightgbm", "extra_trees", "gru", "tcn_1d", "simple_average_top3", "best_per_category"]
sub_cat_filt = sub_cat[sub_cat["model"].isin(cat_key_models)].sort_values(["category", "test_MASE"])
sub_cat_filt.to_csv("results/tables/per_category_h4_summary.csv", index=False)
print(sub_cat_filt.to_string(index=False))
